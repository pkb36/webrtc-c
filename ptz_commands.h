// Command table
static const PtzCommandDef ptz_command_table[] = {
    // Direction commands
    {"up", PTZ_CMD_UP, sizeof(PTZ_CMD_UP), "Move camera up"},
    {"down", PTZ_CMD_DOWN, sizeof(PTZ_CMD_DOWN), "Move camera down"},
    {"left", PTZ_CMD_LEFT, sizeof(PTZ_CMD_LEFT), "Move camera left"},
    {"right", PTZ_CMD_RIGHT, sizeof(PTZ_CMD_RIGHT), "Move camera right"},
    {"enter", PTZ_CMD_ENTER, sizeof(PTZ_CMD_ENTER), "Send enter command"},
    
    // Zoom commands
    {"zoom_init", PTZ_CMD_ZOOM_INIT, sizeof(PTZ_CMD_ZOOM_INIT), "Initialize zoom"},
    
    // Focus commands
    {"AF_Debug_On", PTZ_CMD_AF_DEBUG_ON, sizeof(PTZ_CMD_AF_DEBUG_ON), "Enable AF debug"},
    {"AF_Debug_Off", PTZ_CMD_AF_DEBUG_OFF, sizeof(PTZ_CMD_AF_DEBUG_OFF), "Disable AF debug"},
    {"Focus_Position", PTZ_CMD_FOCUS_POSITION, sizeof(PTZ_CMD_FOCUS_POSITION), "Get focus position"},
    
    // Terminator
    {NULL, NULL, 0, NULL}
};

// Function to find and execute PTZ command
static inline const PtzCommandDef* find_ptz_command(const char *name) {
    for (int i = 0; ptz_command_table[i].name != NULL; i++) {
        if (strcmp(name, ptz_command_table[i].name) == 0) {
            return &ptz_command_table[i];
        }
    }
    return NULL;
}

