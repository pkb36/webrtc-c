static const unsigned char PTZ_CMD_FOCUS_POSITION[] = {0x96, 0x00, 0x14, 0x01, 0x06, 0x81, 0x09, 0x04, 0x19, 0x1F, 0xFF, 0x76};

// Camera mode commands
static const unsigned char PTZ_CMD_DN_AUTO[] = {0x96, 0x00, 0x66, 0x42, 0x01, 0x02, 0x41};
static const unsigned char PTZ_CMD_DN_DAY[] = {0x96, 0x00, 0x66, 0x42, 0x01, 0x00, 0x3f};
