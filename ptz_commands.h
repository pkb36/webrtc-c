static const unsigned char PTZ_CMD_DOWN[] = {0x96, 0x0, 0x14, 0x1, 0x6, 0x81, 0x1, 0x4, 0x16, 0x2, 0xFF, 0x4E};
static const unsigned char PTZ_CMD_LEFT[] = {0x96, 0x0, 0x14, 0x1, 0x6, 0x81, 0x1, 0x4, 0x16, 0x4, 0xFF, 0x50};
static const unsigned char PTZ_CMD_RIGHT[] = {0x96, 0x0, 0x14, 0x1, 0x6, 0x81, 0x1, 0x4, 0x16, 0x8, 0xFF, 0x54};
static const unsigned char PTZ_CMD_ENTER[] = {0x96, 0x0, 0x14, 0x1, 0x6, 0x81, 0x1, 0x4, 0x16, 0x10, 0xFF, 0x5C};

// Zoom commands
static const unsigned char PTZ_CMD_ZOOM_INIT[] = {0x96, 0x0, 0x14, 0x1, 0x6, 0x81, 0x1, 0x4, 0x19, 0x1, 0xFF, 0x50};

// Focus commands
static const unsigned char PTZ_CMD_AF_DEBUG_ON[] = {0x96, 0x00, 0x14, 0x01, 0x08, 0x81, 0x01, 0x04, 0x24, 0x31, 0x00, 0x02, 0xFF, 0x8F};
